#!/usr/bin/env python3
"""
check_media.py — list every image placeholder and placeholder link on the site.

    python scripts/check_media.py            # print status to the terminal
    python scripts/check_media.py --write    # also regenerate MEDIA.md (checklist)

Images: any <figure class="media" data-src="…"> plus the home-page thumbnails
of publications marked selected = {true} (assets/img/pubs/<key>.png unless an
image = {…} field is given). A file that exists replaces its placeholder on the
live site automatically.
Links:  any <a … data-todo="…">.
"""
from __future__ import annotations

import re
import sys
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGES = ["index.html", "publications.html", "projects.html", "teaching.html", "awards.html", "service.html"]


class Scan(HTMLParser):
    def __init__(self, page: str):
        super().__init__()
        self.page, self.media, self.links = page, [], []

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "figure" and "media" in (a.get("class") or ""):
            if a.get("data-src"):
                self.media.append((self.page, a["data-src"], a.get("data-alt") or "", a.get("data-from") or ""))
            elif a.get("data-yt"):
                self.media.append((self.page, f"youtube:{a['data-yt']}", a.get("data-alt") or "", a.get("data-from") or ""))
        if tag == "a" and a.get("data-todo"):
            self.links.append((self.page, a["data-todo"]))


def selected_thumbs() -> list[tuple[str, str, str, str]]:
    bib = (ROOT / "data/publications.bib").read_text("utf-8")
    out = []
    for m in re.finditer(r"@\w+\{([^,]+),(.*?)\n\}", bib, re.S):
        key, body = m.group(1).strip(), m.group(2)
        if re.search(r"selected\s*=\s*\{true\}", body, re.I):
            img = re.search(r"image\s*=\s*\{([^}]*)\}", body)
            out.append(("index.html", img.group(1) if img else f"assets/img/pubs/{key}.png",
                        f"thumbnail for {key}", "Google Site: Publications (selected-paper tiles)"))
    return out


def main() -> int:
    media, links = [], []
    for p in PAGES:
        s = Scan(p)
        s.feed((ROOT / p).read_text("utf-8"))
        media += s.media
        links += s.links
    media += selected_thumbs()

    seen, rows = set(), []
    for page, src, alt, frm in media:
        if src in seen:
            continue
        seen.add(src)
        ok = src.startswith("youtube:") or (ROOT / src).exists()
        rows.append((ok, page, src, alt, frm))

    missing = [r for r in rows if not r[0]]
    print(f"images: {len(rows) - len(missing)}/{len(rows)} present · placeholder links: {len(links)}")
    for ok, page, src, alt, frm in rows:
        print(f"  {'✓' if ok else '·'} {src:58} {page}")

    if "--write" in sys.argv:
        lines = ["# Media & link checklist", "",
                 "Generated by `python scripts/check_media.py --write`. Drop each image at the given path;",
                 "the page swaps the placeholder for the real file automatically (no HTML edit).", "",
                 "Most images are on the old Google Site: open the page, right-click the image →",
                 "*Open image in new tab* → save it under the path below.", "",
                 "## Images", "", "| | file | page | what | source |", "|---|---|---|---|---|"]
        for ok, page, src, alt, frm in rows:
            lines.append(f"| {'✅' if ok else '⬜'} | `{src}` | {page} | {alt} | {frm} |")
        lines += ["", "## Placeholder links", "",
                  "Search the page for `data-todo=\"…\"`, set `href`, then remove the `todo-link` class and the `data-todo` attribute.", "",
                  "| page | link needed |", "|---|---|"]
        for page, what in links:
            lines.append(f"| {page} | {what} |")
        (ROOT / "MEDIA.md").write_text("\n".join(lines) + "\n", "utf-8")
        print("wrote MEDIA.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
